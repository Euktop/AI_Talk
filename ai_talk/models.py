from enum import Enum

class ModelRole(Enum):
    """
    Перечисление ролей/характеристик моделей.
    Скрипты используют эти роли, а не точные названия моделей.
    """
    FAST = "fast"       # Быстрая модель (для тегов, опечаток, простых задач)
    SMART = "smart"     # Умная модель (для глубокого анализа, написания текстов)
    BASE = "base"       # Базовая универсальная модель

# Справочник: какую реальную модель из Ollama использовать для каждой роли.
# Если ты сменишь видеокарту, ты поменяешь названия ТОЛЬКО здесь.
MODEL_REGISTRY = {
    ModelRole.FAST: "qwen2.5:3b",
    ModelRole.SMART: "qwen2.5:7b",  # Или llama3:8b, если хватит VRAM
    ModelRole.BASE: "qwen2.5:3b"
}